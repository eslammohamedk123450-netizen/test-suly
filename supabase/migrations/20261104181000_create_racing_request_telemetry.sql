-- Durable telemetry for API-first provider racing.
CREATE TABLE IF NOT EXISTS public.racing_requests (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id varchar(255) NOT NULL UNIQUE,
  user_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  conversation_id integer REFERENCES public.conversations(id) ON DELETE SET NULL,
  status varchar(30) NOT NULL DEFAULT 'started',
  winning_provider_id integer REFERENCES public.ai_providers(id) ON DELETE SET NULL,
  started_at timestamptz NOT NULL DEFAULT now(),
  first_token_at timestamptz,
  completed_at timestamptz,
  total_duration_ms double precision,
  error_message text
);
CREATE INDEX IF NOT EXISTS ix_racing_requests_user_id ON public.racing_requests(user_id);
CREATE INDEX IF NOT EXISTS ix_racing_requests_conversation_id ON public.racing_requests(conversation_id);
CREATE INDEX IF NOT EXISTS ix_racing_requests_user_created ON public.racing_requests(user_id, started_at);
CREATE INDEX IF NOT EXISTS ix_racing_requests_request_id ON public.racing_requests(request_id);

CREATE TABLE IF NOT EXISTS public.provider_attempts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  racing_request_id integer NOT NULL REFERENCES public.racing_requests(id) ON DELETE CASCADE,
  provider_id integer NOT NULL REFERENCES public.ai_providers(id) ON DELETE CASCADE,
  model_id integer REFERENCES public.ai_models(id) ON DELETE SET NULL,
  status varchar(30) NOT NULL DEFAULT 'started',
  started_at timestamptz NOT NULL DEFAULT now(),
  first_token_at timestamptz,
  completed_at timestamptz,
  failure_reason varchar(500)
);
CREATE INDEX IF NOT EXISTS ix_provider_attempts_racing_request_id ON public.provider_attempts(racing_request_id);
CREATE INDEX IF NOT EXISTS ix_provider_attempts_provider_id ON public.provider_attempts(provider_id);
CREATE INDEX IF NOT EXISTS ix_provider_attempts_model_id ON public.provider_attempts(model_id);

